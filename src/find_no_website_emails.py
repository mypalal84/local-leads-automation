# WEBSITE CHECK — small HEAD request
# ======================================================
def has_live_website(domain):
    """Quickly check if the domain responds with status 200/OK + visible homepage text."""
    if not domain:
        return False

    clean_domain = (domain or "").strip().lower().replace("www.", "")
    if not clean_domain:
        return False

    for candidate in (f"https://{clean_domain}", f"http://{clean_domain}"):
        try:
            resp = requests.get(candidate, headers=HEADERS, timeout=6, allow_redirects=True)
            if 200 <= resp.status_code < 400:
                content_type = (resp.headers.get("Content-Type", "") or "").lower()
                body = (resp.text or "")[:3000]
                if "html" in content_type or re.search(r"<html|<!doctype", body, re.I):
                    return True
        except Exception:
            continue
    return False


def is_confirmed_business_website(url_or_domain: str, business_name: str = "") -> bool:
    value = (url_or_domain or "").strip().lower()
    if not value:
        return False

    parsed = urlparse(value if "://" in value else f"http://{value}")
    domain = (parsed.netloc or parsed.path or "").lower().replace("www.", "").strip()
    if not domain or "." not in domain:
        return False

    if any(domain == d or domain.endswith(f".{d}") for d in DIRECTORY_DOMAIN_HINTS):
        return False

    if domain.endswith(".gov") or domain.endswith(".edu"):
        return False

    return has_live_website(domain)


def is_non_business_domain(domain: str) -> bool:
    clean_domain = (domain or "").strip().lower().replace("www.", "")
    if not clean_domain:
        return True
    return any(
        clean_domain == hint or clean_domain.endswith(f".{hint}")
        for hint in DIRECTORY_DOMAIN_HINTS
    )


def is_viable_email_address(email_addr: str) -> bool:
    value = (email_addr or "").strip().lower()
    if not value or "@" not in value:
        return False
    domain = value.split("@", 1)[1]
    if not domain or "." not in domain:
        return False
    if any(domain == hint or domain.endswith(f".{hint}") for hint in NON_BUSINESS_EMAIL_DOMAIN_HINTS):
        return False
    return True


def filter_viable_emails(emails):
    viable = []
    seen = set()
    for email_addr in emails or []:
        normalized = (email_addr or "").strip().lower()
        if not normalized or normalized in seen:
            continue
        seen.add(normalized)
        if is_viable_email_address(normalized):
            viable.append(normalized)
    return viable

