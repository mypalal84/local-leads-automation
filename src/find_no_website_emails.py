def hunter_email_lookup(domain):
    if not (HUNTER and domain):
        return []
    cached = cache_get("hunter", domain)
    if cached is not None:
        return cached
    def _call():

        def _request():
            r = requests.get("https://api.hunter.io/v2/domain-search",
                             params={"domain": domain, "api_key": HUNTER},
                             timeout=15)
            r.raise_for_status()
            emails = r.json().get("data", {}).get("emails", [])
            return [e.get("value") for e in emails if e.get("value")]

        return run_tracked_api_call("hunter", _request)
    result = retry_request(_call) or []
    cache_set("hunter", domain, result)
    return result


def pre_enrich_base_score(row):
    score = 0
    business_val = row.get("name", "")
    notes_val = row.get("notes", "")
    website_val = row.get("website", "")
    link_val = row.get("link", "")

    business = "" if pd.isna(business_val) else str(business_val).strip()
    notes = "" if pd.isna(notes_val) else str(notes_val).lower()
    website = "" if pd.isna(website_val) else str(website_val).strip()
    link = "" if pd.isna(link_val) else str(link_val).strip().lower()

    if len(business.split()) >= 2:
        score += 1

    if any(token in notes for token in ["under construction", "business.site", "no website"]):
        score += 1

    if website:
        score -= 2

    if link:
        netloc = urlparse(link).netloc.lower().replace("www.", "")
        if any(netloc == d or netloc.endswith(f".{d}") for d in DIRECTORY_DOMAIN_HINTS):
            score -= 1

    if STARTUP_PRIORITY:
        score += startup_signal_score(row)

    return score


def startup_signal_score(row):
    score = 0
    fields = [
        row.get("name", ""),
        row.get("notes", ""),
        row.get("link", ""),
        row.get("website", ""),
    ]
    blob = " ".join("" if pd.isna(v) else str(v) for v in fields).lower()

    if STARTUP_EXCLUDE_TECH and STARTUP_TECH_EXCLUDE_KEYWORDS:
        if any(token in blob for token in STARTUP_TECH_EXCLUDE_KEYWORDS):
            return 0

    # Prefer age-based startup detection over industry/TLD heuristics.
    current_year = datetime.now().year
    year_match = re.search(r"\\b(?:founded|est\\.?|established|since)\\s*(?:in\\s*)?(19\\d{2}|20\\d{2})\\b", blob)
    age_match = False
    if year_match:
        founded_year = int(year_match.group(1))
        age_years = current_year - founded_year
        if 0 <= age_years <= max(0, STARTUP_MAX_AGE_YEARS):
            age_match = True
            score += 1

    young_phrase_match = bool(re.search(r"\\bnewly opened|recently opened|just launched|new business|new company\\b", blob))
    if young_phrase_match:
        score += 1

    # Optional custom hints only count when paired with a young-age signal.
    if STARTUP_HINT_KEYWORDS and any(token in blob for token in STARTUP_HINT_KEYWORDS):
        if age_match or young_phrase_match:
            score += 1

    if score <= 0:
        return 0
    return max(0, STARTUP_SCORE_BOOST)


def can_reach_send_threshold(row, threshold):
    # Best case after enrichment: valid business-domain email (+2)
    # (+1 for having an email, +1 for non-free domain)
    return pre_enrich_base_score(row) + 2 >= threshold

