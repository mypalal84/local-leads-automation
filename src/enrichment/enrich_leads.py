def enrich(service, town, max_leads=None):
    try:
        emit_structured_event(
            "enrichment_start",
            enabled=STRUCTURED_LOGGING_ENABLED,
            service=service,
            city=town,
            max_leads=max_leads,
        )
        safe_town = sanitize_for_filename(town)
        safe_service = sanitize_for_filename(service)

        in_fname = f"leads_{safe_town}_{safe_service}_NO_WEBSITE_{DATESTAMP}.csv"
        in_path = os.path.join(DATA_DIR, in_fname)
        out_path = os.path.join(DATA_DIR, in_fname)

        if not os.path.isfile(in_path):
            legacy_fname = f"leads_{town}_{service}_NO_WEBSITE_{DATESTAMP}.csv"
            legacy_path = os.path.join(DATA_DIR, legacy_fname)
            if os.path.isfile(legacy_path):
                in_fname = legacy_fname
                in_path = legacy_path

        if not os.path.isfile(in_path):
            print(f"[WARN] No discovery data found → {in_path}")
            emit_structured_event(
                "enrichment_missing_input",
                enabled=STRUCTURED_LOGGING_ENABLED,
                service=service,
                city=town,
                input_file=in_path,
            )
            return None

        # Rerun protection: skip if this run's output already exists with non-empty emails.
        if os.path.isfile(out_path):
            try:
                existing_df = pd.read_csv(out_path)
                has_enriched_emails = (
                    "emails" in existing_df.columns
                    and existing_df["emails"].fillna("").astype(str).str.strip().ne("").any()
                )
                if has_enriched_emails:
                    print(f"[SKIP] Enrichment already done for {out_path}")
                    emit_structured_event(
                        "enrichment_skipped_existing_output",
                        enabled=STRUCTURED_LOGGING_ENABLED,
                        service=service,
                        city=town,
                        output_file=out_path,
                    )
                    return out_path
            except Exception:
                # Fall through and run enrichment if we cannot validate existing output.
                pass

        df = pd.read_csv(in_path)
        if df.empty:
            print(f"[WARN] Empty CSV → {town}|{service}")
            return None

        if max_leads is not None:
            max_leads = max(int(max_leads), 0)
            if max_leads == 0:
                print("[INFO] max_leads=0; skipping enrichment work.")
                return in_path
            df = df.head(max_leads)

        enriched, skipped_site, found_emails, skipped_score_floor = [], 0, 0, 0
        print(f"[INFO] Enriching {len(df)} leads for {town.title()} – {service.title()} "
              f"(workers={ENRICH_WORKERS}) …")

        rows = [r.to_dict() for _, r in df.iterrows()]
        with ThreadPoolExecutor(max_workers=ENRICH_WORKERS) as pool:
            futures = [pool.submit(_process_lead, row, town, service) for row in rows]
            for future in as_completed(futures):
                result_row, skip_entirely, s_site, f_email, s_score = future.result()
                if s_site:
                    skipped_site += 1
                if f_email:
                    found_emails += 1
                if s_score:
                    skipped_score_floor += 1
                if not skip_entirely and result_row is not None:
                    enriched.append(result_row)

        if not enriched:
            print(f"[WARN] No usable leads for {town}|{service}")
            emit_structured_event(
                "enrichment_no_usable_leads",
                enabled=STRUCTURED_LOGGING_ENABLED,
                service=service,
                city=town,
            )
            return None

        pd.DataFrame(enriched).drop_duplicates(subset=["name"]).to_csv(out_path, index=False)

        print(f"[✅] Saved {len(enriched)} leads → {out_path}")
        print(f"   ↳ Skipped (business had site): {skipped_site}")
        print(f"   ↳ Skipped (pre‑enrich score floor): {skipped_score_floor}")
        print(f"   ↳ With verified emails: {found_emails}")
        emit_structured_event(
            "enrichment_complete",
            enabled=STRUCTURED_LOGGING_ENABLED,
            service=service,
            city=town,
            total_rows=int(len(enriched)),
            skipped_site=int(skipped_site),
            skipped_score_floor=int(skipped_score_floor),
            verified_email_rows=int(found_emails),
            output_file=out_path,
        )
        return out_path

    except Exception as e:
        print(f"[❌] Fatal error during enrichment: {e}")
        emit_structured_event(
            "enrichment_error",
            enabled=STRUCTURED_LOGGING_ENABLED,
            service=service,
            city=town,
            error=str(e),
        )
        traceback.print_exc()
        return None

