def search_serper(query):
    if not SERPER:
        return []
    cached = cache_get("serper", query)
    if cached is not None:
        return cached
    def _call():
        payload = {"q": query, "num": 5}
        headers = {"X-API-KEY": SERPER, "Content-Type": "application/json"}

        def _request():
            r = post_serper_with_retry(headers=headers, payload=payload, timeout=HTTP_TIMEOUT)
            r.raise_for_status()
            data = r.json().get("organic", [])
            return [x.get("link") for x in data if x.get("link")]

        return run_tracked_api_call("serper", _request)
    result = retry_request(_call) or []
    cache_set("serper", query, result)
    return result

